"""
GeoVision AI — Google Earth Engine Routes
Endpoints for checking Earth Engine status and health.
"""

from typing import Optional
from fastapi import APIRouter, Query
from ..schemas.responses import GEEStatusResponse
from ..services.gee_service import gee_service

router = APIRouter()


@router.get("/gee/status", response_model=GEEStatusResponse)
async def get_gee_status(force_refresh: bool = Query(default=False, description="Force a fresh test request")):
    """
    Get live Google Earth Engine connection status.

    Returns one of:
      - CONNECTED
      - NOT_AUTHENTICATED
      - INVALID_PROJECT
      - REQUEST_FAILED
      - CONFIGURATION_ERROR
    """
    status_data = gee_service.check_gee_connection(force_recheck=force_refresh)
    return GEEStatusResponse(**status_data)


@router.get("/gee/tiles")
async def get_gee_tiles(
    start_year: int = Query(default=2023, ge=2018, le=2026),
    end_year: int = Query(default=2026, ge=2018, le=2026),
    start_month: int = Query(default=1, ge=1, le=12),
    end_month: int = Query(default=4, ge=1, le=12),
    lat: Optional[float] = Query(default=None, ge=-90.0, le=90.0),
    lng: Optional[float] = Query(default=None, ge=-180.0, le=180.0),
    radius_km: Optional[float] = Query(default=None, ge=0.01, le=50.0),
):
    """
    Return XYZ raster tile URL templates generated by Google Earth Engine
    for direct Leaflet layer overlays (True Color, Color Infrared, NDVI, Deltas).
    """
    custom_geom = None
    if lat is not None and lng is not None and gee_service.is_connected:
        try:
            import ee
            r_meters = (radius_km or 25.0) * 1000.0
            custom_geom = ee.Geometry.Point([lng, lat]).buffer(r_meters)
        except Exception:
            pass

    tiles = gee_service.get_map_tile_layers(
        start_year=start_year,
        end_year=end_year,
        start_month=start_month,
        end_month=end_month,
        geometry=custom_geom,
        radius_km=radius_km,
    )
    return tiles
